#!/usr/bin/env node
/** Copy the versioned wire/codec source into the independently deployable Atlas
 * package. Runtime imports must never depend on a sibling checkout on a VPS. */
import { readFile, writeFile } from "node:fs/promises";
import { createHash } from "node:crypto";
const source = new URL("../../Atlas-Link-Dispenser/packages/shared/src/hub.ts", import.meta.url);
const target = new URL("../runtime/hub-contracts.ts", import.meta.url);
const value = await readFile(source, "utf8");
const hash = createHash("sha256").update(value).digest("hex");
const generated = `// Generated by scripts/sync-hub-contracts.mjs; source SHA256 ${hash}\n${value}`;
if (process.argv.includes("--check")) {
  if (await readFile(target,"utf8") !== generated) throw Error("Hub wire contracts differ between release components");
} else await writeFile(target, generated);
console.log(`HUB_CONTRACTS_MATCH ${hash}`);
